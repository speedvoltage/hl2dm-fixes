"""Build/check offline catalogs and the compiled English fallback.

Install tools/asset-requirements.txt first. Languages follow Steam's API list:
https://partner.steamgames.com/doc/store/localization/languages
Translations need native-speaker review before release. No online service is
used by this builder or by the game.
"""
import argparse
import json
from pathlib import Path
from localization import LANGUAGES, resource, validate

def resources(root):
    messages = json.loads((root / 'assets/localization/messages.json').read_text(encoding='utf8'))
    ui = json.loads((root / 'assets/localization/ui.json').read_text(encoding='utf8'))
    assert set(messages['languages']) == LANGUAGES
    assert set(ui['languages']) == LANGUAGES - {'english'}
    assert len(messages['keys']) == len(set(messages['keys']))
    english = {f'HL2MP_{key}': value for key, value in zip(messages['keys'], messages['languages']['english'])}
    for language in sorted(LANGUAGES):
        values = messages['languages'][language]
        assert len(values) == len(messages['keys']), language
        entries = {f'HL2MP_{key}': value for key, value in zip(messages['keys'], values)}
        for key, value in entries.items():
            validate(key, english[key], value)
        yield root / f'game/mod_hl2mp/resource/hl2mp_messages_{language}.txt', resource(language, entries, wrap=True)
        translated = ui['languages'].get(language, {})
        if language != 'english':
            assert set(translated) == set(ui['entries']), (language, 'Catalog keys differ')
        entries = {}
        for key, item in ui['entries'].items():
            value = item['english'] if language == 'english' else translated[key]
            validate(f'{language}/{key}', item['english'], value)
            entries[key] = value
        yield root / f'game/mod_hl2mp/resource/hl2mp_ui_{language}.txt', resource(language, entries)
    def cpp(value):
        if value is None:
            return 'NULL'
        return '"' + ''.join(chr(c) if 32 <= c < 127 and c not in (34, 92) else '\\%03o' % c for c in value.encode('utf8')) + '"'
    rows = [(key, value, None) for key, value in english.items()]
    rows += [(key, item['english'], item.get('format')) for key, item in ui['entries'].items()]
    lines = ['// Generated by tools/build-localization.py. Edit assets/localization instead.', 'static const Message s_Messages[] = {']
    lines += ['    { %s, %s, %s },' % tuple(map(cpp, row)) for row in rows]
    lines += ['};', '']
    yield root / 'src/game/client/hl2mp/ui/hl2mp_messages_fallback.inc', '\n'.join(lines).encode('ascii')

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    count = 0
    for path, data in resources(Path(__file__).resolve().parents[1]):
        if args.check:
            assert path.read_bytes() == data, f'Regenerate {path.name}'
        else:
            path.write_bytes(data)
        count += 1
    print(f'{count} localization outputs checked' if args.check else f'{count} localization outputs built')

if __name__ == '__main__':
    main()
